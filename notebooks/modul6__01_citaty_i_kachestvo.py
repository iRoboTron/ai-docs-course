for ident, vopros in VOPROSY:
    kuski = nayti(vopros)
    rezultat = sprosit_json(vopros, kuski)
    ok, lishnie = proverit_chisla(rezultat, kuski)
    print(f"{ident:<12} {'✅' if ok else '❌':<8} {sorted(lishnie) or '—'}")

