# %% [markdown]
# ## Шаг 9. Готовый фреймворк оценки: RAGAS `[пишем вместе]`
#
# Всё, что мы делали руками — эталонный набор, проверка кодом, судья, — на работе уже
# упаковано в готовые инструменты.
#
# > **Фреймворк для оценки** (по-английски *evaluation framework*) — готовый инструмент,
# > который прогоняет эталонный набор через ИИ-систему, считает метрики и отдаёт число.
# > Ничего писать самому не нужно — только дать вопросы, ответы и эталоны.
#
# Конкретно для RAG есть фреймворк с говорящим названием **RAGAS** (*RAG + assessment*,
# «оценка»). Он считает две вещи, которые мы как раз делим в модуле 5 и 6:
#
# > **context_recall** — полнота поиска: все ли утверждения из правильного ответа
# > подтверждаются найденными кусками. Низкая — поиск не донёс нужное.
# >
# > **faithfulness** — правдивость ответа: каждое ли утверждение ответа подтверждается
# > найденными кусками. Низкая — модель додумала, хотя в кусках этого нет.
#
# Обе метрики считаются моделью-судьёй внутри фреймворка — той самой, чьи слабости мы
# разбирали в шаге 7. То есть числа RAGAS стоит перепроверять, а не принимать на веру.
#
# **Одна оговорка про наш набор.** RAGAS предполагает, что у каждого вопроса есть правильный
# ответ. А у нас есть вопрос «оплатить картой?», на который правильный ответ — «в документах
# этого нет». Для отказа фреймворк не задуман: он выдаст бесполезные нули. Поэтому такой
# вопрос исключаем и считаем отказ нашей собственной проверкой, как в шаге 6.
#
# **Цена шага:** каждая метрика по каждому вопросу делает несколько запросов к модели —
# десятки вызовов. На дешёвой модели это копейки, но внутри школьного лимита запросов
# в час шаг заметен.

