# %% [markdown]
# ## Шаг 2. Ответ с цитатой `[пишем вместе]`
#
# Гостю мало правильного ответа: полезно знать, откуда он. А нам — ещё полезнее: по цитате
# можно **проверить кодом**, что бот не выдумал.
